-- ============================================================
-- PROBADOR VIRTUAL INTELIGENTE - VESTIDOR VIRTUAL
-- Script para Supabase (PostgreSQL). Es el mismo modelo de base_datos/probador_virtual_mysql.sql
-- pasado a Postgres: las mismas cinco tablas y las mismas columnas.
--
--   tienda    los locales que usan el probador, con su equipo
--   prenda    cada prenda con sus colores, talles (y medidas) y stock
--   clientes  los clientes con su programa de fidelidad (nivel, puntos, cupones, favoritos)
--   prueba    cada vez que alguien se prueba una prenda con la cámara (sin imágenes)
--   compra    cada compra, con sus prendas y sus descuentos
--
-- Diferencias con MySQL: JSON -> jsonb, ENUM -> text con CHECK, AUTO_INCREMENT -> identity.
-- Seguridad: las tablas tienen RLS activado y SIN políticas, así nadie las puede leer ni
-- cambiar con las claves públicas de Supabase. Sólo la API de la página (que se conecta
-- como el dueño de la base) las usa.
-- No borra nada: se puede ejecutar más de una vez.
-- ============================================================

-- 1. Tiendas físicas que usan el sistema.
-- equipos: [{"tipo": "pantalla" | "camara" | "computadora", "ubicacion", "estado"}]
CREATE TABLE IF NOT EXISTS tienda (
    id_tienda integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(120) NOT NULL,
    direccion varchar(255),
    ciudad varchar(100),
    telefono varchar(30),
    email varchar(150),
    equipos jsonb,
    estado text NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa', 'inactiva')),
    fecha_creacion timestamptz NOT NULL DEFAULT now()
);

-- 2. Prendas del catálogo.
-- colores: [{"nombre", "hex", "es_foto"}]  talles: [{"talle", "pecho", ...}]
-- stock:   {"Azul Marino|M": {"sku": "VV-0011-AZM-M", "stock": 5}, ...}
CREATE TABLE IF NOT EXISTS prenda (
    id_prenda integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(80) NOT NULL UNIQUE,
    sku varchar(20) UNIQUE,
    nombre varchar(150) NOT NULL,
    descripcion text,
    categoria varchar(80) NOT NULL,
    genero text NOT NULL DEFAULT 'unisex' CHECK (genero IN ('mujer', 'hombre', 'unisex', 'infantil')),
    precio numeric(10,2) NOT NULL CHECK (precio >= 0),
    calce text NOT NULL DEFAULT 'regular' CHECK (calce IN ('entallado', 'regular', 'holgado')),
    imagen_url varchar(500) NOT NULL,
    ajuste_foto jsonb,
    colores jsonb NOT NULL CHECK (jsonb_typeof(colores) = 'array'),
    talles jsonb NOT NULL CHECK (jsonb_typeof(talles) = 'array'),
    stock jsonb NOT NULL CHECK (jsonb_typeof(stock) = 'object'),
    estado text NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa', 'inactiva')),
    fecha_creacion timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_prenda_categoria ON prenda (categoria);

-- 3. Clientes y su programa de fidelidad (las reglas de cada nivel están en tienda.py).
-- cupones: [{"codigo", "descripcion", "tipo", "valor", "compra_minima", "vence", "usado", "creado"}]
-- favoritos: [id_prenda, ...]
CREATE TABLE IF NOT EXISTS clientes (
    id_cliente integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(80) NOT NULL,
    apellido varchar(80),
    email varchar(150) NOT NULL UNIQUE,
    telefono varchar(30),
    fecha_nacimiento date,
    talle_preferido varchar(20),
    acepta_promociones boolean NOT NULL DEFAULT false,
    nivel text NOT NULL DEFAULT 'Bronce' CHECK (nivel IN ('Bronce', 'Plata', 'Oro', 'Diamante')),
    puntos integer NOT NULL DEFAULT 0 CHECK (puntos >= 0),
    total_gastado numeric(12,2) NOT NULL DEFAULT 0,
    cupones jsonb,
    favoritos jsonb,
    fecha_alta timestamptz NOT NULL DEFAULT now(),
    ultima_visita timestamptz
);

-- 4. Pruebas: qué prenda, en qué color y talle, cuánto tiempo y si terminó en compra.
-- Nunca se guardan fotos ni video.
CREATE TABLE IF NOT EXISTS prueba (
    id_prueba integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prenda integer NOT NULL REFERENCES prenda (id_prenda) ON UPDATE CASCADE ON DELETE CASCADE,
    id_cliente integer REFERENCES clientes (id_cliente) ON UPDATE CASCADE ON DELETE SET NULL,
    id_tienda integer REFERENCES tienda (id_tienda) ON UPDATE CASCADE ON DELETE SET NULL,
    tipo text NOT NULL DEFAULT 'online' CHECK (tipo IN ('tienda', 'online')),
    color varchar(50),
    talle varchar(20),
    segundos integer NOT NULL DEFAULT 0 CHECK (segundos >= 0),
    compro boolean NOT NULL DEFAULT false,
    fecha timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_prueba_fecha ON prueba (fecha);
CREATE INDEX IF NOT EXISTS idx_prueba_prenda ON prueba (id_prenda);
CREATE INDEX IF NOT EXISTS idx_prueba_cliente ON prueba (id_cliente);
CREATE INDEX IF NOT EXISTS idx_prueba_tienda ON prueba (id_tienda);

-- 5. Compras: una fila por compra completa.
-- detalle: [{"id_prenda", "sku", "nombre", "color", "talle", "cantidad", "precio"}]
CREATE TABLE IF NOT EXISTS compra (
    id_compra integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente integer REFERENCES clientes (id_cliente) ON UPDATE CASCADE ON DELETE SET NULL,
    id_tienda integer REFERENCES tienda (id_tienda) ON UPDATE CASCADE ON DELETE SET NULL,
    id_prueba integer REFERENCES prueba (id_prueba) ON UPDATE CASCADE ON DELETE SET NULL,
    detalle jsonb NOT NULL CHECK (jsonb_typeof(detalle) = 'array'),
    subtotal numeric(12,2) NOT NULL,
    descuento_nivel numeric(12,2) NOT NULL DEFAULT 0,
    descuento_cupon numeric(12,2) NOT NULL DEFAULT 0,
    descuento_puntos numeric(12,2) NOT NULL DEFAULT 0,
    total numeric(12,2) NOT NULL,
    cupon varchar(30),
    puntos_usados integer NOT NULL DEFAULT 0,
    puntos_ganados integer NOT NULL DEFAULT 0,
    estado text NOT NULL DEFAULT 'pagada' CHECK (estado IN ('pendiente', 'pagada', 'cancelada', 'entregada')),
    fecha timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_compra_total CHECK (total >= 0 AND subtotal >= 0)
);
CREATE INDEX IF NOT EXISTS idx_compra_fecha ON compra (fecha);
CREATE INDEX IF NOT EXISTS idx_compra_cliente ON compra (id_cliente);
CREATE INDEX IF NOT EXISTS idx_compra_tienda ON compra (id_tienda);
CREATE INDEX IF NOT EXISTS idx_compra_prueba ON compra (id_prueba);

-- Nadie entra por la API pública de Supabase (sin políticas = sin acceso con las claves públicas)
ALTER TABLE tienda ENABLE ROW LEVEL SECURITY;
ALTER TABLE prenda ENABLE ROW LEVEL SECURITY;
ALTER TABLE clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE prueba ENABLE ROW LEVEL SECURITY;
ALTER TABLE compra ENABLE ROW LEVEL SECURITY;
